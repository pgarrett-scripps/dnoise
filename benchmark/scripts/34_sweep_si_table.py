#!/usr/bin/env python3
"""Emit the SI default-parameter-sweep table (paper/si/param_sweep.typ) and copy
the sweep figures into paper/figures/.

Merges results/dda_15min/sweep/{sweep_metrics.csv, sweep_fidelity.csv} into one
Typst table: per arm (raw, streak grid, intensity-threshold control) the MS1 data
reduction, quantified peptides (delta vs raw), quantified proteins, median CV, and
intensity fidelity vs raw (median |log2| and within +-10%). The chosen default
(gap2/len5) is marked. Run after 31_sweep_analyze.py and 33_sweep_fidelity.py.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SWEEP = ROOT / "results" / "dda_15min" / "sweep"
PAPER = ROOT.parent / "paper"
DEFAULT_ARM = "g2_l5"


def label(row) -> str:
    if row["arm"] == "original":
        return "original (raw)"
    if row["kind"] == "intensity":
        return f"intensity T={int(row['T'])}"
    return f"gap {int(row['gap'])}, len {int(row['len'])}"


def main() -> int:
    m = pd.read_csv(SWEEP / "sweep_metrics.csv")
    f = pd.read_csv(SWEEP / "sweep_fidelity.csv")[
        ["arm", "med_abs_log2", "within_10pct"]]
    df = m.merge(f, on="arm", how="left")
    raw_pep = int(df.loc[df["arm"] == "original", "quant_peptides"].iloc[0])

    # Order: raw, streak grid by (gap,len), then intensity control by reduction.
    streak = df[(df["kind"] == "streak") & (df["arm"] != "original")].sort_values(
        ["gap", "len"])
    intens = df[df["kind"] == "intensity"].sort_values("ms1_reduction_pct")
    orig = df[df["arm"] == "original"]
    ordered = pd.concat([orig, streak, intens])

    lines = [
        "// AUTO-GENERATED by scripts/34_sweep_si_table.py -- do not edit by hand.",
        "#table(",
        "  columns: 7,",
        "  align: (left,) + (right,) * 6,",
        "  table.header(",
        "    [Setting], [MS1], [Peptides], [Proteins],",
        "    [Median], [Med.], [Within],",
        "  ),",
        "  table.hline(),",
        "  [], [removed], [(#sym.Delta raw)], [(#sym.gt.eq 2 pep.)],",
        "  [CV], [$|log_2|$], [#sym.plus.minus 10%],",
        "  table.hline(),",
    ]
    for _, r in ordered.iterrows():
        is_default = r["arm"] == DEFAULT_ARM
        name = label(r)
        if is_default:
            name = f"*{name}* #super[a]"
        if r["arm"] == "original":
            red = "#sym.dash.em"
            dpep = f"{int(r['quant_peptides']):,}"
            fid, within = "#sym.dash.em", "#sym.dash.em"
        else:
            red = f"{r['ms1_reduction_pct']:.0f}%"
            d = int(r["quant_peptides"]) - raw_pep
            dpep = f"{int(r['quant_peptides']):,} ({'+' if d >= 0 else '#sym.minus '}{abs(d)})"
            fid = f"{r['med_abs_log2']:.3f}"
            within = f"{r['within_10pct']*100:.0f}%"
        row = (f"  [{name}], [{red}], [{dpep}], [{int(r['quant_proteins']):,}], "
               f"[{r['median_cv']:.3f}], [{fid}], [{within}],")
        lines.append(row)
    lines.append(")")

    out = PAPER / "si" / "param_sweep.typ"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")

    for src, dst in [("sweep_quant.png", "si_param_sweep_quant.png"),
                     ("sweep_fidelity.png", "si_param_sweep_fidelity.png")]:
        shutil.copy(SWEEP / src, PAPER / "figures" / dst)
        print(f"copied {src} -> figures/{dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
