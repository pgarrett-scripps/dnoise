#!/usr/bin/env python3
"""Generate Typst table fragments for the Supporting Information.

Writes to paper/si/ (one #table(...) per file, included by supplementary.typ):
  per_run_<dataset>.typ  -- per-run data reduction (peaks + binary) for a gradient
  accuracy_all.typ       -- full LFQ accuracy: observed vs expected, every
                            pair x species x arm x gradient
Also prints MS/MS precursor-fragmentation statistics (frames per precursor) used
in SI section S5.

Usage: uv run scripts/17_si_tables.py [dataset ...]   (default: dda_5min dda_15min)
"""

from __future__ import annotations

import re
import sqlite3
import sys
from collections import Counter
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SI = ROOT.parent / "paper" / "si"
ARMS_SUMMARY = ["original", "denoised", "msms"]   # accuracy.csv arm tags
ARM_LABEL = {"original": "orig.", "denoised": "MS1", "msms": "+MS/MS"}
GRAD_LABEL = {"dda_5min": "5 min", "dda_15min": "15 min",
              "dia_5min": "5 min", "dia_15min": "15 min"}
SPECIES = ["HUMAN", "YEAST", "ECOLI"]
PAIRS = ["A/B", "A/C", "B/C"]


def esc(s: str) -> str:
    return str(s).replace("/", "\\/")


def per_run_table(dataset: str) -> None:
    p = ROOT / "results" / dataset / "analysis" / "data_reduction.csv"
    if not p.is_file():
        print(f"  skip per-run {dataset}: no {p}")
        return
    df = pd.read_csv(p).sort_values("file")
    cols = ["Run", "MS1 (M)", "MS1 kept", "MS2 (M)", "MS2 kept", "bin raw", "bin MS1", "bin +MS\\/MS"]
    lines = [
        "// AUTO-GENERATED by scripts/17_si_tables.py -- do not edit by hand.",
        "#table(",
        "  columns: 8,",
        "  align: (left, right, right, right, right, right, right, right),",
        "  table.header(" + ", ".join(f"[{c}]" for c in cols) + "),",
    ]
    for _, r in df.iterrows():
        ms1_keep = 100 * r["ms1_MS1"] / r["ms1_raw"] if r["ms1_raw"] else 0
        ms2_keep = 100 * r["ms2_MS1+MS/MS"] / r["ms2_raw"] if r["ms2_raw"] else 0
        cells = [
            f"[{r['file']}]",
            f"[{r['ms1_raw']/1e6:.0f}]",
            f"[{ms1_keep:.0f}%]",
            f"[{r['ms2_raw']/1e6:.0f}]",
            f"[{ms2_keep:.0f}%]",
            f"[{r['bytes_raw']/1e6:.0f}]",
            f"[{r['bytes_MS1']/1e6:.0f}]",
            f"[{r['bytes_MS1+MS/MS']/1e6:.0f}]",
        ]
        lines.append("  " + ", ".join(cells) + ",")
    # Aggregate (total) row: peak/byte columns summed; kept-% pooled (weighted by
    # raw points), matching the 18-run aggregates quoted in the main text.
    tot_ms1_raw = df["ms1_raw"].sum()
    tot_ms2_raw = df["ms2_raw"].sum()
    agg_ms1_keep = 100 * df["ms1_MS1"].sum() / tot_ms1_raw if tot_ms1_raw else 0
    agg_ms2_keep = 100 * df["ms2_MS1+MS/MS"].sum() / tot_ms2_raw if tot_ms2_raw else 0
    tot_cells = [
        "[*Total*]",
        f"[*{tot_ms1_raw/1e6:.0f}*]",
        f"[*{agg_ms1_keep:.0f}%*]",
        f"[*{tot_ms2_raw/1e6:.0f}*]",
        f"[*{agg_ms2_keep:.0f}%*]",
        f"[*{df['bytes_raw'].sum()/1e6:.0f}*]",
        f"[*{df['bytes_MS1'].sum()/1e6:.0f}*]",
        f"[*{df['bytes_MS1+MS/MS'].sum()/1e6:.0f}*]",
    ]
    lines.append("  table.hline(),")
    lines.append("  " + ", ".join(tot_cells) + ",")
    lines.append(")")
    out = SI / f"per_run_{dataset}.typ"
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out}  ({len(df)} runs)")


def accuracy_table(datasets: list[str], out_name: str = "accuracy_all.typ") -> None:
    accs = {}
    for d in datasets:
        p = ROOT / "results" / d / "analysis" / "accuracy.csv"
        if p.is_file():
            accs[d] = pd.read_csv(p)
    if not accs:
        print("  skip accuracy: no accuracy.csv")
        return
    grads = list(accs)
    arms = ARMS_SUMMARY
    ncol = 2 + len(grads) * len(arms)   # pair/species label, expected, then grad x arm
    lines = [
        "// AUTO-GENERATED by scripts/17_si_tables.py -- do not edit by hand.",
        "#table(",
        f"  columns: {ncol},",
        "  align: (left,) + (right,) * " + str(ncol - 1) + ",",
        "  table.header(",
        "    table.cell(rowspan: 2)[Pair, species], table.cell(rowspan: 2)[exp.],",
        "    " + ", ".join(f"table.cell(colspan: {len(arms)})[{GRAD_LABEL.get(g, g)}]" for g in grads) + ",",
        "    " + ", ".join(f"[{ARM_LABEL[a]}]" for _ in grads for a in arms) + ",",
        "  ),",
    ]
    for pair in PAIRS:
        for sp in SPECIES:
            exp = None
            cells = []
            for g in grads:
                a = accs[g]
                sub = a[(a["pair"] == pair) & (a["species"] == sp)]
                for arm in arms:
                    row = sub[sub["arm"] == arm]
                    if len(row):
                        exp = float(row["expected"].iloc[0])
                        obs = float(row["observed"].iloc[0])
                        if {"ci_lo", "ci_hi"}.issubset(row.columns) and pd.notna(row["ci_lo"].iloc[0]):
                            lo, hi = float(row["ci_lo"].iloc[0]), float(row["ci_hi"].iloc[0])
                            cells.append(f"[{obs:+.2f} \\ #text(size: 7pt)[({lo:.2f}, {hi:.2f})]]")
                        else:
                            cells.append(f"[{obs:+.2f}]")
                    else:
                        cells.append("[--]")
            exp_s = f"[{exp:+.2f}]" if exp is not None else "[--]"
            label = f"[{pair} {sp[:1] + sp[1:].lower()}]"
            lines.append("  " + ", ".join([label, exp_s] + cells) + ",")
    lines.append(")")
    out = SI / out_name
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out}")


def per_replicate_quant_table(datasets: list[str], out_name: str = "per_replicate_quant.typ") -> None:
    """Per-replicate quantified-protein counts (two-peptide rule) for each arm and
    gradient: mean +/- SD across the (up to six) replicates of each condition. Shows
    that the cross-arm coverage gains exceed run-to-run variability."""
    import sys as _sys
    _sys.path.insert(0, str(Path(__file__).resolve().parent))
    import _metrics as M

    dda = [d for d in datasets if d.startswith("dda")]
    if not dda:
        return
    cells_by_arm: dict[str, list[str]] = {a: [] for a in ARMS_SUMMARY}
    have = {a: False for a in ARMS_SUMMARY}
    for g in dda:
        for arm in ARMS_SUMMARY:
            d = ROOT / "results" / g / arm
            if not (d / "lfq.tsv").is_file():
                cells_by_arm[arm] += ["[--]", "[--]", "[--]"]
                continue
            have[arm] = True
            prot, fcols = M._rollup(d)
            for c in "ABC":
                cc = [x for x in fcols if M.condition_of(x) == c]
                if not cc:
                    cells_by_arm[arm].append("[--]")
                    continue
                per = prot[cc].notna().sum(axis=0).values
                cells_by_arm[arm].append(f"[{per.mean():.0f} #sym.plus.minus {per.std(ddof=1):.0f}]")
    grads = dda
    ncol = 1 + 3 * len(grads)
    lines = [
        "// AUTO-GENERATED by scripts/17_si_tables.py -- do not edit by hand.",
        "#table(",
        f"  columns: {ncol},",
        "  align: (left,) + (right,) * " + str(ncol - 1) + ",",
        "  table.header(",
        "    table.cell(rowspan: 2)[Arm],",
        "    " + ", ".join(f"table.cell(colspan: 3)[{GRAD_LABEL.get(g, g)}]" for g in grads) + ",",
        "    " + ", ".join("[A], [B], [C]" for _ in grads) + ",",
        "  ),",
    ]
    for arm in ARMS_SUMMARY:
        if not have[arm]:
            continue
        lines.append("  " + ", ".join([f"[{ARM_LABEL[arm]}]"] + cells_by_arm[arm]) + ",")
    lines.append(")")
    out = SI / out_name
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out}")


def centroider_table(out_name: str = "centroider.typ") -> None:
    """Full original vs watershed vs box centroider comparison (5-minute ddaPASEF):
    data reduction, identifications (identical, MS/MS untouched), and LFQ coverage /
    precision / accuracy under the two-peptide rule. Mirrors the main-text Fig 5."""
    import sys as _sys
    _sys.path.insert(0, str(Path(__file__).resolve().parent))
    import _metrics as M

    DATA = ROOT / "data" / "dda_5min"
    RES = ROOT / "results" / "dda_5min"
    arms = [("Orig.", "raw", "original"), ("Watershed", "watershed", "watershed"),
            ("Box", "box", "box")]
    if not all((RES / rsub / "lfq.tsv").is_file() for _, _, rsub in arms):
        print("  skip centroider table: missing original/watershed/box arm")
        return

    def comp(dsub: str) -> tuple[int, int]:
        ms1 = b = 0
        for d in sorted((DATA / dsub).glob("*.d")):
            a, _, bb = M.stats(d)
            ms1 += a
            b += bb
        return ms1, b

    o_ms1, o_bin = comp("raw")
    C = []
    for lab, dsub, rsub in arms:
        ms1, b = comp(dsub)
        idm = M.id_metrics(RES / rsub)
        lm = M.lfq_metrics(M.lfq_table(RES / rsub), RES / rsub)
        C.append({"ms1_rm": 100 * (1 - ms1 / o_ms1) if o_ms1 else 0,
                  "bin": 100 * b / o_bin if o_bin else 0, **idm, **lm})

    def row(label, fmt):
        return "  " + ", ".join([f"[{label}]"] + [f"[{fmt(c)}]" for c in C]) + ","

    def signed(v):  # Typst-safe signed log2: minus sign as #sym.minus
        return f"#sym.minus {abs(v):.2f}" if v < 0 else f"+{v:.2f}"

    dash = "#sym.dash.em"
    lines = [
        "// AUTO-GENERATED by scripts/17_si_tables.py -- do not edit by hand.",
        "#table(",
        "  columns: 4,",
        "  align: (left, center, center, center),",
        "  table.header([Metric], [Orig.], [Watershed], [Box]),",
        row("MS1 peaks removed", lambda c: dash if c["ms1_rm"] < 0.1 else f"{c['ms1_rm']:.1f}%"),
        row("Frame binary (% of raw)", lambda c: f"{c['bin']:.1f}%"),
        row("PSMs (1% FDR)", lambda c: f"{c['n_psm']:,}"),
        row("Peptides (1% FDR)", lambda c: f"{c['n_peptide']:,}"),
        row("Protein groups (1% FDR)", lambda c: f"{c['n_protein']:,}"),
        row("Proteins quantified ($gt.eq$2 pep.)", lambda c: f"{c['n_quantified']:,}"),
        row("#sym.space.quad yeast", lambda c: f"{c['n_YEAST']:,}"),
        row("#sym.space.quad _E. coli_", lambda c: f"{c['n_ECOLI']:,}"),
        row("Peptides quantified", lambda c: f"{c['n_quant_peptide']:,}"),
        row("Median CV", lambda c: f"{c['median_cv']:.3f}"),
        row("$log_2(A/B)$ human (exp. 0)", lambda c: signed(c["median_log2_HUMAN"])),
        row("$log_2(A/B)$ yeast (exp. +1)", lambda c: signed(c["median_log2_YEAST"])),
        row("$log_2(A/B)$ _E. coli_ (exp. #sym.minus 2)", lambda c: signed(c["median_log2_ECOLI"])),
        row("MAD human / yeast / _E. coli_",
            lambda c: f"{c['mad_HUMAN']:.2f}/{c['mad_YEAST']:.2f}/{c['mad_ECOLI']:.2f}"),
        ")",
    ]
    out = SI / out_name
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out}")


def fragmentation_stats(dataset: str) -> None:
    raw = sorted((ROOT / "data" / dataset / "raw").glob("*.d"))
    if not raw:
        print(f"  (no raw .d in {dataset} for fragmentation stats)")
        return
    d = raw[0]
    c = sqlite3.connect(d / "analysis.tdf")
    counts = [n for _, n in c.execute(
        "SELECT Precursor, COUNT(*) FROM PasefFrameMsMsInfo GROUP BY Precursor")]
    c.close()
    counts.sort()
    n = len(counts)
    med = counts[n // 2]
    mean = sum(counts) / n
    dist = Counter(counts)
    print(f"\nMS/MS fragmentation ({d.name}): {n} precursors; "
          f"frames/precursor median {med}, mean {mean:.2f}, max {max(counts)}")
    print("  distribution:", {k: dist[k] for k in sorted(dist)})


def copy_config() -> None:
    """Copy dnoise.toml into paper/si/ so supplementary.typ can embed it
    (Typst sandboxes reads to the paper project root)."""
    for name in ("dnoise.toml", "sage.json"):
        src = ROOT / "config" / name
        if not src.is_file():
            continue
        text = src.read_text()
        if name == "sage.json":
            # Sanitize the machine-specific absolute FASTA path and per-arm output dir
            # so the deposited config is portable.
            text = re.sub(r'"fasta":\s*"[^"]*"',
                          '"fasta": "data/fasta/hybrid.fasta"', text)
            text = re.sub(r'"output_directory":\s*"[^"]*"',
                          '"output_directory": "results/<arm>"', text)
        (SI / name).write_text(text)
        print(f"Copied {src.name} -> {SI / name}")


def main() -> int:
    datasets = sys.argv[1:] or ["dda_5min", "dda_15min"]
    SI.mkdir(parents=True, exist_ok=True)
    for d in datasets:
        per_run_table(d)
    # Separate DDA and DIA accuracy tables (parallel, one per acquisition).
    dda = [d for d in datasets if d.startswith("dda")]
    dia = [d for d in datasets if d.startswith("dia")]
    if dda:
        accuracy_table(dda, "accuracy_all.typ")
        per_replicate_quant_table(dda)
        centroider_table()
    if dia:
        accuracy_table(dia, "accuracy_dia.typ")
    copy_config()
    fragmentation_stats(datasets[0])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
